# Report of the acceptance sweep: results.csv and docs/ACCEPTANCE.md (included by run_dynare_tests.jl).
const CATS = ["OK", "OK_WARN", "CHECK_FAILED", "REFUSED", "ERROR", "TIMEOUT", "XFAIL", "XPASS", "SKIPPED"]
const CAT_DOC = Dict(
    "OK" => "ran to the end, no warning",
    "OK_WARN" => "ran to the end, but JDyn skipped MATLAB lines or commands (its own checks may not have run)",
    "CHECK_FAILED" => "the file's own error()/assert() fired",
    "REFUSED" => "ModelError / Unsupported / EstimationError: a clearly named unsupported feature",
    "ERROR" => "raw Julia exception, interpreter error or preprocessor failure",
    "TIMEOUT" => "over the per-test limit",
    "XFAIL" => "`should_fail` in meson.build and failed too (as expected)",
    "XPASS" => "`should_fail` in meson.build but ran without error",
    "SKIPPED" => ".m script (unit test of Dynare's MATLAB library, data script), not a model run")

struct Row
    id::String; test::String; cat::String; secs::Float64; nwarn::Int; etype::String; msg::String; warns::String
end

function read_rows(dir=HERE)
    rows = Row[]
    for d in sort(filter(d -> startswith(d, "partial"), readdir(dir)))
        f = joinpath(dir, d, "results.tsv"); isfile(f) || continue
        for l in eachline(f)
            p = split(l, TAB; keepempty=true)
            length(p) < 7 && continue
            push!(rows, Row(p[1], p[2], p[3], something(tryparse(Float64, p[4]), 0.0), something(tryparse(Int, p[5]), 0), p[6], p[7], length(p) >= 8 ? p[8] : ""))
        end
    end
    rows
end

"Normalise a message so that failures with one root cause share a key."
function cause_key(r::Row)
    r.cat == "CHECK_FAILED" && return "check: " * first(r.msg, 80)
    m = r.cat == "OK_WARN" ? first(split(r.warns, " || ")) : r.msg
    r.cat == "OK_WARN" && occursin("not executed (", m) && (m = replace(m, r"^MATLAB code in the \.mod file: \d+ statement\(s\) not executed " => "MATLAB lines not executed "); m = first(split(m, ". In them"))
    m = replace(m, r"/[\w./+-]+" => "<path>")
    m = replace(m, r"\d+(\.\d+)?(e[-+]?\d+)?" => "N")
    m = replace(m, r"'[^']*'" => "'_'")
    m = replace(m, r"\"[^\"]*\"" => "\"_\"")
    m = replace(m, r"\s+" => " ")
    (r.etype == "" || r.cat == "OK_WARN" ? "" : r.etype * ": ") * first(m, 110)
end

csvq(s) = "\"" * replace(String(s), "\"" => "\"\"") * "\""
function write_csv(rows, out)
    open(out, "w") do io
        println(io, "entry,test,category,seconds,warnings,exception,cause,message,warning_text")
        for r in rows
            println(io, join([csvq(r.id), csvq(r.test), r.cat, r.secs, r.nwarn, csvq(r.etype), csvq(cause_key(r)), csvq(r.msg), csvq(r.warns)], ","))
        end
    end
end

topdir(t) = startswith(t, "../") ? "examples" : (occursin('/', t) ? first(split(t, '/')) : "(root)")

function counts(rows, f)
    d = Dict{String,Dict{String,Int}}()
    for r in rows
        k = f(r); c = get!(d, k, Dict{String,Int}()); c[r.cat] = get(c, r.cat, 0) + 1
    end
    d
end

function causes_table(io, rows, cat; top=25, examples=3)
    rs = filter(r -> r.cat == cat, rows)
    isempty(rs) && return
    g = Dict{String,Vector{Row}}()
    for r in rs; push!(get!(g, cause_key(r), Row[]), r); end
    ks = sort(collect(keys(g)); by=k -> (-length(g[k]), k))
    println(io, "\n#### $cat by cause ($(length(rs)) tests, $(length(ks)) causes)\n")
    println(io, "| n | cause | examples |\n|---:|---|---|")
    for k in ks[1:min(top, end)]
        ex = join(["`" * replace(r.test, r"^\.\./" => "") * "`" for r in g[k][1:min(examples, end)]], ", ")
        println(io, "| $(length(g[k])) | ", replace(k, "|" => "\\|"), " | ", ex, " |")
    end
    length(ks) > top && println(io, "\n($(length(ks) - top) further causes with fewer tests are in results.csv.)")
end

function load_baseline()
    f = joinpath(HERE, "results_before.csv")
    isfile(f) || return nothing
    d = Dict{String,Int}()
    for (i, l) in enumerate(eachline(f))
        i == 1 && continue
        m = match(r"^\"[^\"]*(?:\"\"[^\"]*)*\",\"[^\"]*(?:\"\"[^\"]*)*\",([A-Z_]+),", l)
        m === nothing || (d[m[1]] = get(d, m[1], 0) + 1)
    end
    d
end

function write_reports(out)
    rows = read_rows()
    isempty(rows) && (println("no results"); return)
    write_csv(rows, out)
    md = joinpath(ROOT, "docs", "ACCEPTANCE.md")
    base = load_baseline()
    open(md, "w") do io
        n = length(rows)
        println(io, "# Acceptance: Dynare 7.2's own test suite through `JDyn.dynare`\n")
        println(io, "Generated by `test/acceptance/run_dynare_tests.jl` (manifest: the `mod_and_m_tests` list of Dynare's `meson.build`,")
        println(io, "with its `extra` files, per-entry scratch directory, test order and `-D` options, as `scripts/test-driver` runs them;")
        println(io, "`.mod` files that are only `@#include`d are not tests). $n tests; per-test limit and seconds in `results.csv`.\n")
        c = Dict(k => count(r -> r.cat == k, rows) for k in CATS)
        println(io, "## Result\n")
        if base === nothing
            println(io, "| category | tests | meaning |\n|---|---:|---|")
            for k in CATS; println(io, "| $k | $(c[k]) | $(CAT_DOC[k]) |"); end
        else
            println(io, "| category | before | after | meaning |\n|---|---:|---:|---|")
            for k in CATS; println(io, "| $k | $(get(base, k, 0)) | $(c[k]) | $(CAT_DOC[k]) |"); end
            println(io, "| total | $(sum(values(base))) | $n | |")
        end
        println(io)
        println(io, "Time: $(round(sum(r.secs for r in rows) / 60; digits=1)) min of test time; slowest: ",
                join(["`$(r.test)` $(round(Int, r.secs)) s" for r in sort(rows; by=r -> -r.secs)[1:min(5, n)]], ", "), ".\n")
        println(io, "## By directory\n")
        d = counts(rows, r -> topdir(r.test))
        println(io, "| directory | ", join(CATS, " | "), " |\n|---|", repeat("---:|", length(CATS)))
        for k in sort(collect(keys(d)); by=k -> (-sum(values(d[k])), k))
            println(io, "| $k | ", join([get(d[k], x, 0) for x in CATS], " | "), " |")
        end
        println(io, "\n## Causes")
        for cat in ("CHECK_FAILED", "ERROR", "REFUSED", "TIMEOUT", "OK_WARN")
            causes_table(io, rows, cat; top=cat == "CHECK_FAILED" ? 100 : 30)
        end
    end
    println("wrote ", out, " and ", md)
end
