# Classification of every OccBin .mod file of Dynare 7.2's tests/ and examples/ (the files containing an
# occbin_constraints block). Used by test/test_obc.jl and, run as a script, writes docs/OBC_CLASSIFICATION.md:
#   julia --project=. test/obc/classify_dynare.jl [dynare-7.2 source tree]
using JDyn, Logging

"The .mod files under `src`/tests and `src`/examples with an occbin_constraints block (relative paths, sorted)."
function occbin_mod_files(src)
    out = String[]
    for top in ("tests", "examples"), (root, _, files) in walkdir(joinpath(src, top)), f in files
        endswith(f, ".mod") || continue
        p = joinpath(root, f)
        occursin("occbin_constraints", read(p, String)) && push!(out, relpath(p, src))
    end
    sort(out)
end

"Load a copy of the file's folder (include files, data); rows of the classification, or the error if it does not load."
function classify_file(src, rel)
    d = mktempdir()
    srcdir = dirname(joinpath(src, rel))
    for f in readdir(srcdir)
        p = joinpath(srcdir, f)
        isfile(p) && cp(p, joinpath(d, f))
    end
    allow0 = JDyn.ALLOW_RANDOM[]
    JDyn.ALLOW_RANDOM[] = true          # as dynare() does: the files' randn draws (shock sequences) do not matter here
    m = try
        with_logger(NullLogger()) do
            JDyn.load(joinpath(d, basename(rel)))
        end
    catch e
        return (rows=nothing, error=first(replace(sprint(showerror, e), r"\s+" => " "), 160))
    finally
        JDyn.ALLOW_RANDOM[] = allow0
    end
    rows = try
        obc_classification(m)
    catch e
        return (rows=nothing, error=first(replace(sprint(showerror, e), r"\s+" => " "), 160))
    end
    (rows=rows, error="")
end

function classification_markdown(src)
    files = occbin_mod_files(src)
    io = IOBuffer()
    println(io, "# Classification of Dynare 7.2's OccBin models for `obc_method = minnorm / news`\n")
    println(io, "Generated by `test/obc/classify_dynare.jl` from the Dynare 7.2 source tree (every `.mod` file under `tests/` and `examples/`",
            " with an `occbin_constraints` block) and locked in by `test/test_obc.jl`. Classes and signs are defined in src/obc.jl",
            " (`obc_constraints`) and docs/OBC_PROGRESS.md. `s_g`, `s_y`: signs of gap (`g = s_g * alt_resid`) and wedge (`y = s_y * ref_resid`).",
            " Only `complementarity` constraints can be solved by `minnorm` and `news`; a model needs all its constraints in that class.\n")
    println(io, "| File | Constraint | Class | Equation(s) | s_g | s_y | bind / relax | Reason |")
    println(io, "|---|---|---|---|---|---|---|---|")
    counts = Dict{String,Int}()
    for rel in files
        r = classify_file(src, rel)
        if r.rows === nothing
            println(io, "| `$rel` | - | not loaded | - | - | - | - | ", replace(r.error, "|" => "\\|"), " |")
            counts["not loaded (file)"] = get(counts, "not loaded (file)", 0) + 1
            continue
        end
        for x in r.rows
            br = "`" * x.bind * "`" * (isempty(x.relax) ? "" : " / `" * x.relax * "`")
            println(io, "| `$rel` | $(x.constraint) | $(x.class) | $(x.equation) | $(x.s_g) | $(x.s_y) | ", replace(br, "|" => "\\|"), " | ",
                    replace(x.why, "|" => "\\|"), " |")
            counts[String(x.class)] = get(counts, String(x.class), 0) + 1
        end
    end
    println(io, "\nTotals: ", join(["$k: $v" for (k, v) in sort(collect(counts))], ", "), " (", length(files), " files).")
    String(take!(io)), files, counts
end

if abspath(PROGRAM_FILE) == @__FILE__
    src = length(ARGS) >= 1 ? ARGS[1] : get(ENV, "JDYN_DYNARE_SRC", "/home/claude/ref/dynare-7.2")
    md, files, counts = classification_markdown(src)
    write(joinpath(@__DIR__, "..", "..", "docs", "OBC_CLASSIFICATION.md"), md)
    print(md)
end
